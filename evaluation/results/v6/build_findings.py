#!/usr/bin/env python3
"""Extract portable Findings evidence; --check verifies it without changing files."""

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent


def build():
    source = (ROOT / "accepted-runs.json").read_bytes()
    data = json.loads(source)
    runs = []
    for run in data["runs"]:
        if run["view"] != "models":
            continue
        runs.append({key: run[key] for key in (
            "id", "group", "sample", "effort", "core_final", "maintenance_final",
            "final_failed_families",
        )})
    result = {
        "dataset_sha256": hashlib.sha256(source).hexdigest(),
        "runs": runs,
    }
    return "// Generated by build_findings.py from accepted-runs.json.\nconst findingsEvidence = " + json.dumps(result, indent=2) + ";\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "findings-data.js"
    expected = build()
    if args.check:
        if target.read_text() != expected:
            raise SystemExit("Findings evidence differs from the accepted dataset")
        print("Findings evidence verified: all 73 model-view runs and failed family outcomes.")
    else:
        target.write_text(expected)
        print("Wrote", target)
